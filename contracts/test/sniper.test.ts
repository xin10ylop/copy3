import {
  decodeErrorResult,
  decodeEventLog,
  decodeFunctionResult,
  encodeDeployData,
  encodeFunctionData,
  parseEther,
  type Abi,
  type Hex,
} from 'viem';
import { beforeAll, beforeEach, describe, expect, it } from 'vitest';
// plain JS build script (typed via JSDoc), shared with the tests
import { compileFiles } from '../script/compile.mjs';
import { sniperAbi, sniperBytecode } from '../src/index.js';
import { Chain, type Signer, type TxResult } from './helpers/evm.js';

interface Artifact {
  abi: Abi;
  bytecode: Hex;
}
const LAUNCH_TS = 1_792_758_495n;
const PHANTOM = 1_680_000_000_000_000_000n; // AMLIL launch: 1.68 ETH phantom quote
const SUPPLY = 10n ** 27n;
const CREATOR_TAX = 200n;

let mock: Artifact;
let ALL_ABI: Abi;
const gas: Record<string, bigint> = {};

beforeAll(() => {
  const out = compileFiles(['test/mocks/MockPonsCurve.sol', 'src/PonsSniper.sol']) as Record<string, Artifact>;
  mock = out.MockPonsCurve!;
  // the committed generated bytecode must match a fresh compile
  expect(out.PonsSniper!.bytecode).toBe(sniperBytecode);
  ALL_ABI = [...sniperAbi, ...mock.abi, ...out.MockToken!.abi] as Abi;
});

function revertName(r: TxResult): string {
  expect(r.ok).toBe(false);
  try {
    const e = decodeErrorResult({ abi: ALL_ABI, data: r.returnData });
    return `${e.errorName}(${(e.args ?? []).map(String).join(',')})`;
  } catch {
    return r.error ?? 'unknown';
  }
}

function events(r: TxResult): { eventName: string; args: Record<string, unknown>; address: Hex }[] {
  return r.logs.flatMap((l) => {
    try {
      const d = decodeEventLog({ abi: ALL_ABI, data: l.data, topics: l.topics as [Hex, ...Hex[]] });
      return [{ eventName: String(d.eventName), args: d.args as unknown as Record<string, unknown>, address: l.address }];
    } catch {
      return [];
    }
  });
}

describe('PonsSniper (in-process EVM, Cancun)', () => {
  let chain: Chain;
  let owner: Signer;
  let operator: Signer;
  let stranger: Signer;
  let curve: Hex;
  let token: Hex;
  let sniper: Hex;

  const snipeData = (o: { quoteIn?: bigint; minOut?: bigint; maxTax?: number; deadline?: bigint } = {}): Hex =>
    encodeFunctionData({
      abi: sniperAbi,
      functionName: 'snipe',
      args: [curve, token, o.quoteIn ?? parseEther('0.035'), o.minOut ?? 0n, o.maxTax ?? 1000, o.deadline ?? 1_000n],
    });

  const read = async (to: Hex, abi: Abi, functionName: string, args: unknown[] = []): Promise<unknown> =>
    decodeFunctionResult({ abi, functionName, data: await chain.call(to, encodeFunctionData({ abi, functionName, args })) });

  beforeEach(async () => {
    chain = await Chain.create();
    owner = chain.signer(1);
    operator = chain.signer(2);
    stranger = chain.signer(3);
    for (const s of [owner, operator, stranger]) await chain.fund(s.address, parseEther('100'));
    chain.setBlock(90n, LAUNCH_TS);
    const c = await chain.send(owner, {
      data: encodeDeployData({ abi: mock.abi, bytecode: mock.bytecode, args: [PHANTOM, SUPPLY, CREATOR_TAX, LAUNCH_TS] }),
    });
    expect(c.ok).toBe(true);
    curve = c.createdAddress!;
    token = (await read(curve, mock.abi, 'token')) as Hex;
    const s = await chain.send(owner, {
      data: encodeDeployData({ abi: sniperAbi, bytecode: sniperBytecode, args: [owner.address, operator.address] }),
    });
    expect(s.ok).toBe(true);
    sniper = s.createdAddress!;
    expect(await read(sniper, sniperAbi as Abi, 'arbBlockNumbers')).toBe(false);
    expect((await chain.send(owner, { to: sniper, value: parseEther('1') })).ok).toBe(true); // fund via receive()
  });

  it('launch-second block: TaxTooHigh(9900) reverts cheaply (< 40k gas)', async () => {
    chain.setBlock(100n, LAUNCH_TS);
    const r = await chain.send(operator, { to: sniper, data: snipeData() });
    expect(revertName(r)).toBe('TaxTooHigh(9900)');
    expect(r.gasUsed).toBeLessThan(40_000n);
    gas.taxTooHigh = r.gasUsed;
  });

  it('deadline expiry reverts first (cheapest path)', async () => {
    chain.setBlock(1_001n, LAUNCH_TS + 1n);
    const r = await chain.send(operator, { to: sniper, data: snipeData({ deadline: 1_000n }) });
    expect(revertName(r)).toBe('Expired()');
    gas.expired = r.gasUsed;
    expect(r.gasUsed).toBeLessThan(25_000n);
  });

  it('non-operator is rejected', async () => {
    chain.setBlock(100n, LAUNCH_TS + 1n);
    const r = await chain.send(stranger, { to: sniper, data: snipeData() });
    expect(revertName(r)).toBe('NotOperator()');
    for (const fn of [
      encodeFunctionData({ abi: sniperAbi, functionName: 'exit', args: [curve, token, 1n, 0n] }),
      encodeFunctionData({ abi: sniperAbi, functionName: 'sweepEth', args: [stranger.address, 0n] }),
      encodeFunctionData({ abi: sniperAbi, functionName: 'setOperator', args: [stranger.address, true] }),
    ]) {
      expect((await chain.send(stranger, { to: sniper, data: fn })).ok).toBe(false);
    }
    // operator may snipe/exit but not administer
    expect(
      revertName(await chain.send(operator, { to: sniper, data: encodeFunctionData({ abi: sniperAbi, functionName: 'sweepEth', args: [operator.address, 0n] }) })),
    ).toBe('NotOwner()');
  });

  it('successful snipe at +1 s: buys once, holds tokens, approves curve, emits Sniped', async () => {
    chain.setBlock(101n, LAUNCH_TS + 1n);
    const quoteIn = parseEther('0.035');
    const r = await chain.send(operator, { to: sniper, data: snipeData({ quoteIn }) });
    expect(r.ok).toBe(true);
    gas.snipeSuccess = r.gasUsed;
    const ev = events(r);
    const sniped = ev.find((e) => e.eventName === 'Sniped')!;
    // same math as the first taxed AMLIL buyer (fixture): 618 bps snipe tax + 1 % fee + 2 % creator tax
    const net = quoteIn - (quoteIn * 618n) / 10_000n - (quoteIn * 100n) / 10_000n - (quoteIn * 200n) / 10_000n;
    const expectedOut = (SUPPLY * net) / (PHANTOM + net);
    expect({ ...sniped.args, token: String(sniped.args.token).toLowerCase(), curve: String(sniped.args.curve).toLowerCase() }).toMatchObject({
      token: token.toLowerCase(),
      curve: curve.toLowerCase(),
      quoteIn,
      tokensOut: expectedOut,
      taxBps: 618n,
    });
    expect(ev.find((e) => e.eventName === 'SnipeTaxCharged')!.args).toMatchObject({ amount: (quoteIn * 618n) / 10_000n });
    expect(await read(token, ALL_ABI, 'balanceOf', [sniper])).toBe(expectedOut);
    expect(await read(sniper, sniperAbi as Abi, 'bought', [token])).toBe(true);
    expect(await read(token, ALL_ABI, 'allowance', [sniper, curve])).toBe(2n ** 256n - 1n);
    expect(await chain.balance(sniper)).toBe(parseEther('1') - quoteIn);

    // second member after success: AlreadyBought, cheap
    const again = await chain.send(operator, { to: sniper, data: snipeData({ quoteIn }) });
    expect(revertName(again)).toBe('AlreadyBought()');
    gas.alreadyBought = again.gasUsed;
    expect(again.gasUsed).toBeLessThan(30_000n);
  });

  it('slippage failure bubbles the curve error and leaves bought[token] unset', async () => {
    chain.setBlock(101n, LAUNCH_TS + 1n);
    const r = await chain.send(operator, { to: sniper, data: snipeData({ minOut: 10n ** 27n }) });
    expect(revertName(r)).toMatch(/^SlippageExceeded\(/);
    expect(await read(sniper, sniperAbi as Abi, 'bought', [token])).toBe(false);
  });

  it('exit sells and forwards ETH to the owner; exitAll sells the rest', async () => {
    chain.setBlock(101n, LAUNCH_TS + 1n);
    expect((await chain.send(operator, { to: sniper, data: snipeData() })).ok).toBe(true);
    const held = (await read(token, ALL_ABI, 'balanceOf', [sniper])) as bigint;
    const ownerBefore = await chain.balance(owner.address);
    const sniperBefore = await chain.balance(sniper);
    chain.setBlock(130n, LAUNCH_TS + 4n);
    const r = await chain.send(operator, {
      to: sniper,
      data: encodeFunctionData({ abi: sniperAbi, functionName: 'exit', args: [curve, token, held / 2n, 1n] }),
    });
    expect(r.ok).toBe(true);
    gas.exit = r.gasUsed;
    const exited = events(r).find((e) => e.eventName === 'Exited')!;
    const quoteOut = exited.args.quoteOut as bigint;
    expect(quoteOut).toBeGreaterThan(0n);
    expect(await chain.balance(owner.address)).toBe(ownerBefore + quoteOut);
    expect(await chain.balance(sniper)).toBe(sniperBefore);
    const r2 = await chain.send(operator, {
      to: sniper,
      data: encodeFunctionData({ abi: sniperAbi, functionName: 'exitAll', args: [curve, token, 0n] }),
    });
    expect(r2.ok).toBe(true);
    expect(await read(token, ALL_ABI, 'balanceOf', [sniper])).toBe(0n);
    const nothing = await chain.send(operator, {
      to: sniper,
      data: encodeFunctionData({ abi: sniperAbi, functionName: 'exitAll', args: [curve, token, 0n] }),
    });
    expect(revertName(nothing)).toBe('NothingToSell()');
  });

  it('burst of 5 across the second boundary: exactly one buy executes', async () => {
    const plan: [bigint, bigint][] = [
      [100n, LAUNCH_TS], // lands in launch-second blocks → TaxTooHigh
      [101n, LAUNCH_TS],
      [102n, LAUNCH_TS + 1n], // first +1 s block → buy
      [102n, LAUNCH_TS + 1n], // same block, after the success → AlreadyBought
      [103n, LAUNCH_TS + 1n],
    ];
    const results: string[] = [];
    let buys = 0;
    let totalGas = 0n;
    for (const [n, ts] of plan) {
      chain.setBlock(n, ts);
      const r = await chain.send(operator, { to: sniper, data: snipeData() });
      totalGas += r.gasUsed;
      buys += events(r).filter((e) => e.eventName === 'CurveBuy').length;
      results.push(r.ok ? 'ok' : revertName(r));
    }
    expect(results).toEqual(['TaxTooHigh(9900)', 'TaxTooHigh(9900)', 'ok', 'AlreadyBought()', 'AlreadyBought()']);
    expect(buys).toBe(1);
    gas.burstOf5 = totalGas;
  });

  it('a curve that rejects contract callers makes snipe revert (RESEARCH §7.2 must-verify)', async () => {
    expect((await chain.send(owner, { to: curve, data: encodeFunctionData({ abi: mock.abi, functionName: 'setEoaOnly', args: [true] }) })).ok).toBe(true);
    chain.setBlock(101n, LAUNCH_TS + 1n);
    const r = await chain.send(operator, { to: sniper, data: snipeData() });
    expect(r.ok).toBe(false);
    expect(await read(sniper, sniperAbi as Abi, 'bought', [token])).toBe(false);
  });

  it('owner admin: setOperator, sweepEth, sweepToken, rescue', async () => {
    const d = (functionName: string, args: unknown[]): Hex =>
      encodeFunctionData({ abi: sniperAbi as Abi, functionName, args });
    expect((await chain.send(owner, { to: sniper, data: d('setOperator', [stranger.address, true]) })).ok).toBe(true);
    chain.setBlock(101n, LAUNCH_TS + 1n);
    expect((await chain.send(stranger, { to: sniper, data: snipeData() })).ok).toBe(true);
    expect((await chain.send(owner, { to: sniper, data: d('setOperator', [stranger.address, false]) })).ok).toBe(true);
    expect((await chain.send(stranger, { to: sniper, data: snipeData() })).ok).toBe(false);

    const cold = chain.signer(99).address;
    const bal = await chain.balance(sniper);
    expect((await chain.send(owner, { to: sniper, data: d('sweepEth', [cold, 0n]) })).ok).toBe(true);
    expect(await chain.balance(cold)).toBe(bal);
    const held = (await read(token, ALL_ABI, 'balanceOf', [sniper])) as bigint;
    expect((await chain.send(owner, { to: sniper, data: d('sweepToken', [token, cold, 0n]) })).ok).toBe(true);
    expect(await read(token, ALL_ABI, 'balanceOf', [cold])).toBe(held);
    // rescue: arbitrary call (approve 0 to the curve through the token)
    const approveZero = encodeFunctionData({ abi: ALL_ABI, functionName: 'approve', args: [curve, 0n] });
    const r = await chain.send(owner, { to: sniper, data: d('rescue', [token, 0n, approveZero]) });
    expect(r.ok).toBe(true);
    expect(await read(token, ALL_ABI, 'allowance', [sniper, curve])).toBe(0n);
  });

  it('report gas', () => {
    // eslint-disable-next-line no-console
    console.log('[gas]', JSON.stringify(Object.fromEntries(Object.entries(gas).map(([k, v]) => [k, Number(v)]))));
  });
});
