#!/usr/bin/env node
/**
 * Compile contracts with solc-js (no Foundry/Hardhat needed).
 *   node script/compile.mjs        → artifacts/PonsSniper.json + src/generated/PonsSniper.ts
 * Also exported as a library (`compileFiles`) so tests compile the mocks with identical settings.
 *
 * Settings: optimizer on, 200 runs, evmVersion cancun (Robinhood Chain = Nitro ArbOS 61, which
 * supports Shanghai/Cancun opcodes incl. PUSH0 and MCOPY). Tests execute the bytecode in an
 * in-process @ethereumjs VM at the Cancun hardfork.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import solc from 'solc';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const SOLC_SETTINGS = {
  optimizer: { enabled: true, runs: 200 },
  evmVersion: 'cancun',
  outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object', 'evm.methodIdentifiers'] } },
};

/**
 * @param {string[]} files absolute or contracts-relative .sol paths
 * @returns {Record<string, {abi: unknown[], bytecode: `0x${string}`, deployedBytecode: `0x${string}`, methodIdentifiers: Record<string,string>}>}
 */
export function compileFiles(files) {
  const sources = {};
  for (const f of files) {
    const abs = resolve(ROOT, f);
    sources[basename(abs)] = { content: readFileSync(abs, 'utf8') };
  }
  const out = JSON.parse(solc.compile(JSON.stringify({ language: 'Solidity', sources, settings: SOLC_SETTINGS })));
  const errors = (out.errors ?? []).filter((e) => e.severity === 'error');
  if (errors.length) throw new Error(errors.map((e) => e.formattedMessage).join('\n'));
  /** @type {Record<string, any>} */
  const result = {};
  for (const [, contracts] of Object.entries(out.contracts ?? {})) {
    for (const [name, c] of Object.entries(contracts)) {
      result[name] = {
        abi: c.abi,
        bytecode: `0x${c.evm.bytecode.object}`,
        deployedBytecode: `0x${c.evm.deployedBytecode.object}`,
        methodIdentifiers: c.evm.methodIdentifiers,
      };
    }
  }
  return result;
}

export const solcVersion = () => solc.version();

function main() {
  const { PonsSniper } = compileFiles(['src/PonsSniper.sol']);
  mkdirSync(join(ROOT, 'artifacts'), { recursive: true });
  writeFileSync(
    join(ROOT, 'artifacts', 'PonsSniper.json'),
    JSON.stringify({ contractName: 'PonsSniper', abi: PonsSniper.abi, bytecode: PonsSniper.bytecode, deployedBytecode: PonsSniper.deployedBytecode, compiler: { solc: solc.version(), ...SOLC_SETTINGS, outputSelection: undefined } }, null, 2),
  );
  mkdirSync(join(ROOT, 'src', 'generated'), { recursive: true });
  const ts = `// AUTO-GENERATED by contracts/script/compile.mjs — do not edit. Re-run \`pnpm --filter @hood/contracts build\`.
// solc ${solc.version()}, optimizer 200 runs, evmVersion ${SOLC_SETTINGS.evmVersion}
export const ponsSniperAbi = ${JSON.stringify(PonsSniper.abi, null, 2)} as const;

export const ponsSniperBytecode = '${PonsSniper.bytecode}' as const;

export const ponsSniperDeployedBytecode = '${PonsSniper.deployedBytecode}' as const;

export const ponsSniperCompiler = { solc: '${solc.version()}', evmVersion: '${SOLC_SETTINGS.evmVersion}', optimizerRuns: 200 } as const;
`;
  writeFileSync(join(ROOT, 'src', 'generated', 'PonsSniper.ts'), ts);
  console.log(`PonsSniper: ${(PonsSniper.deployedBytecode.length - 2) / 2} bytes runtime, ${(PonsSniper.bytecode.length - 2) / 2} bytes initcode`);
  for (const [sig, sel] of Object.entries(PonsSniper.methodIdentifiers)) console.log(`  0x${sel}  ${sig}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
